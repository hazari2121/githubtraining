# Excel workbook with ready-made PivotTables and slicers for exploring the data
# without code: compare insects, host trees, countries and years by clicking.
#
# Excel builds the PivotTables when the file is opened (they are stored as a recipe),
# so the pivot sheets look empty in tools other than Excel / LibreOffice.

suppressPackageStartupMessages({
  library(dplyr)
})

pivot_data <- function(model_data) {
  grp <- grep("^grp_", names(model_data), value = TRUE)
  # host / climate columns exist only when the host-climate file was given
  for (v in c("damage_rel", "host_amount", "vpd", "tas", "pr"))
    if (!v %in% names(model_data)) model_data[[v]] <- NA_real_
  model_data |>
    transmute(
      country, region_code = nuts, region, year = as.integer(year),
      insect = coalesce(insect, sp_code), sp_code, guild = coalesce(guild, "aggregate"),
      host, host_type, unit, damage = value,
      damage_rel_pct = 100 * damage_rel, host_amount,
      vpd, temperature = tas, precipitation = pr,
      aggregate_code = if_else(is_aggregate, "yes", "no"),
      paper_series = if_else(in_paper_series, "yes", "no"),
      across(all_of(grp), ~ if_else(.x, "yes", "no"))
    ) |>
    rename_with(~ sub("^grp_", "group_", .x), starts_with("grp_"))
}

pivot_how_to <- function() {
  data.frame(`How to use this workbook` = c(
    "Each blue tab is a PivotTable on the 'data' sheet. Click a slicer button (Ctrl+click for several) to filter.",
    "Drag fields in the PivotTable Fields panel to make any other combination; all fields of 'data' are available.",
    "Each table is split by unit: m3 = damaged wood (borers), ha = defoliated area (defoliators). Never add the two together.",
    "Blank cell = no record (not recorded). 0 = monitored, no damage. These are different.",
    "damage_rel_pct = damage as % of the host amount in that region (empty if no host data).",
    "Ips typographus as in the paper: filter group_ips_typographus = yes (includes the combined spruce bark beetle code).",
    "Paper-style analysis: filter paper_series = yes (series with at least 6 years of damage).",
    "aggregate_code = yes marks codes that combine several insects; set it to 'no' when comparing species.",
    "If a PivotTable looks empty or out of date: Data > Refresh All.",
    "This file is regenerated by the pipeline (Rscript run_pipeline.R ...). Do not edit the data here; changes are lost."
  ), check.names = FALSE)
}

write_pivot_workbook <- function(model_data, path) {
  if (!requireNamespace("openxlsx2", quietly = TRUE)) {
    warning("Package openxlsx2 not installed; pivot workbook skipped.")
    return(invisible(NULL))
  }
  library(openxlsx2)
  df <- pivot_data(model_data)

  wb <- wb_workbook() |>
    wb_add_worksheet("how to use") |>
    wb_add_data(x = pivot_how_to()) |>
    wb_set_col_widths(cols = 1, widths = 120) |>
    wb_add_worksheet("data") |>
    wb_add_data_table(x = df, table_name = "damage", na = "") |>
    wb_freeze_pane(first_row = TRUE)

  # name, rows, cols, value, function, slicers
  # "unit" is always the first row level, so m3 (borers) and ha (defoliators) are never
  # added together.
  specs <- list(
    list("insect by year",    "insect",  "year",    "damage",         "sum",     c("unit", "guild", "host", "country")),
    list("insect by country", "insect",  "country", "damage",         "sum",     c("unit", "guild", "host", "year")),
    list("insect vs tree",    "insect",  "host",    "damage",         "sum",     c("unit", "guild", "country")),
    list("tree by year",      "host",    "year",    "damage",         "sum",     c("unit", "guild", "country")),
    list("tree by country",   "host",    "country", "damage",         "sum",     c("unit", "guild", "year")),
    list("country by year",   "country", "year",    "damage",         "sum",     c("unit", "guild", "insect", "host")),
    list("relative damage",   "insect",  "country", "damage_rel_pct", "average", c("unit", "guild", "host")),
    list("records count",     "insect",  "country", "damage",         "count",   c("guild", "host", "year"))
  )

  df_x <- wb_data(wb, sheet = "data")
  for (i in seq_along(specs)) {
    s <- specs[[i]]
    nm <- paste0("pt", i)
    filt <- setdiff(c("aggregate_code", "paper_series"), c(s[[2]], s[[3]]))
    wb <- wb |>
      wb_add_worksheet(s[[1]], tab_color = wb_color("4472C4")) |>
      wb_add_pivot_table(df_x, sheet = s[[1]], dims = "C3",
                         rows = unique(c("unit", s[[2]])), cols = s[[3]], data = s[[4]], fun = s[[5]],
                         filter = filt, slicer = setdiff(s[[6]], c("unit", s[[2]], s[[3]])),
                         pivot_table = nm,
                         params = list(table_style = "TableStyleMedium9", compact = FALSE, row_grand_totals = FALSE,
                                       outline = FALSE))
    sl <- setdiff(s[[6]], c("unit", s[[2]], s[[3]]))
    for (j in seq_along(sl))
      wb <- wb |> wb_add_slicer(df_x, sheet = s[[1]], dims = paste0("A", 3 + (j - 1) * 14),
                                pivot_table = nm, slicer = sl[j])
    wb <- wb |> wb_set_col_widths(sheet = s[[1]], cols = 1:4, widths = c(22, 2, 8, 30))
  }

  wb_save(wb, path, overwrite = TRUE)
  invisible(path)
}
