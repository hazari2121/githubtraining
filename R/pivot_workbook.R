  ), check.names = FALSE)
}

# Host matrices (1 = the insect lives on that tree, 0 = not), with Latin tree names.
# Built from build_host_tables(), the same tables that reproduce the hand-made
# HOST_tables workbook. Aggregate codes are left out, as in that workbook.
host_matrix_tables <- function(host, refs = read_host_references()) {
  labels <- refs$hosts |> distinct(host, host_label, order) |> arrange(order)
  lab <- setNames(labels$host_label, labels$host)

  # one wide table: insects x all host trees
  wide <- host$insect_hosts |>
    mutate(v = 1, host = factor(lab[host], levels = unique(labels$host_label))) |>
    select(code, host, v) |>
    tidyr::pivot_wider(names_from = host, values_from = v, values_fill = 0,
                       names_expand = TRUE)
  all_matrix <- host$insects |>
    select(insect, code, guild, host_type, regions, countries, host_amount_source) |>
    left_join(wide, by = "code")

  # the four boxes, as in the example workbook
  boxes <- lapply(host$matrices, function(m) {
    m$`host tree` <- unname(lab[m$`host tree`])
    m
  })
  list(all = all_matrix, boxes = boxes)
}

write_pivot_workbook <- function(model_data, path, host = NULL) {
  if (!requireNamespace("openxlsx2", quietly = TRUE)) {
    warning("Package openxlsx2 not installed; pivot workbook skipped.")
    return(invisible(NULL))
  }
  library(openxlsx2)
  df <- pivot_data(model_data)

  wb <- wb_workbook() |>
    wb_add_worksheet("how to use") |>
    wb_add_data(x = pivot_how_to()) |>
    wb_set_col_widths(cols = 1, widths = 120) |>
    wb_add_worksheet("data") |>
    wb_add_data_table(x = df, table_name = "damage", na = "") |>
    wb_freeze_pane(first_row = TRUE)

  # name, rows, cols, value, function, slicers
  # "unit" is always the first row level, so m3 (borers) and ha (defoliators) are never
  # added together.
  specs <- list(
    list("insect by year",    "insect",  "year",    "damage",         "sum",     c("unit", "guild", "host_tree", "country")),
    list("insect by country", "insect",  "country", "damage",         "sum",     c("unit", "guild", "host_tree", "year")),
    list("insect vs tree",    "insect",  "host_tree",    "damage",         "sum",     c("unit", "guild", "country")),
    list("tree by year",      "host_tree",    "year",    "damage",         "sum",     c("unit", "guild", "country")),
    list("tree by country",   "host_tree",    "country", "damage",         "sum",     c("unit", "guild", "year")),
    list("country by year",   "country", "year",    "damage",         "sum",     c("unit", "guild", "insect", "host_tree")),
    list("relative damage",   "insect",  "country", "damage_rel_pct", "average", c("unit", "guild", "host_tree")),
    list("records count",     "insect",  "country", "damage",         "count",   c("guild", "host_tree", "year"))
  )

  df_x <- wb_data(wb, sheet = "data")
  for (i in seq_along(specs)) {
    s <- specs[[i]]
    nm <- paste0("pt", i)
    filt <- setdiff(c("aggregate_code", "paper_series"), c(s[[2]], s[[3]]))
    wb <- wb |>
      wb_add_worksheet(s[[1]], tab_color = wb_color("4472C4")) |>
      wb_add_pivot_table(df_x, sheet = s[[1]], dims = "C3",
                         rows = unique(c("unit", s[[2]])), cols = s[[3]], data = s[[4]], fun = s[[5]],
                         filter = filt, slicer = setdiff(s[[6]], c("unit", s[[2]], s[[3]])),
                         pivot_table = nm,
                         params = list(table_style = "TableStyleMedium9", compact = FALSE, row_grand_totals = FALSE,
                                       outline = FALSE))
    sl <- setdiff(s[[6]], c("unit", s[[2]], s[[3]]))
    for (j in seq_along(sl))
      wb <- wb |> wb_add_slicer(df_x, sheet = s[[1]], dims = paste0("A", 3 + (j - 1) * 14),
                                pivot_table = nm, slicer = sl[j])
    wb <- wb |> wb_set_col_widths(sheet = s[[1]], cols = 1:4, widths = c(22, 2, 8, 30))
  }

  if (!is.null(host)) {
    hm <- host_matrix_tables(host)
    wb <- wb |> wb_add_dxfs_style(name = "is_host", bg_fill = wb_color("C6EFCE"),
                                  font_color = wb_color("006100"))
    green <- wb_color("70AD47")

    # all insects x all host trees, filterable / sortable by 1 or 0
    n_fix <- 7
    wb <- wb |>
      wb_add_worksheet("host matrix", tab_color = green) |>
      wb_add_data_table(x = hm$all, table_name = "host_matrix",
                        table_style = "TableStyleLight11") |>
      wb_add_conditional_formatting(
        dims = wb_dims(x = hm$all, cols = (n_fix + 1):ncol(hm$all)),
        rule = "==1", type = "expression", style = "is_host") |>
      wb_set_col_widths(cols = seq_len(ncol(hm$all)),
                        widths = c(34, 12, 11, 12, 9, 10, 20, rep(16, ncol(hm$all) - n_fix))) |>
      wb_freeze_pane(first_active_row = 2, first_active_col = 2)

    # the four boxes of the example sheet
    for (b in names(hm$boxes)) {
      m <- hm$boxes[[b]]
      wb <- wb |>
        wb_add_worksheet(b, tab_color = green) |>
        wb_add_data(x = m) |>
        wb_add_conditional_formatting(dims = wb_dims(x = m, cols = 2:ncol(m)),
                                      rule = "==1", type = "expression", style = "is_host") |>
        wb_set_col_widths(cols = seq_len(ncol(m)), widths = c(32, rep(14, ncol(m) - 1))) |>
        wb_freeze_pane(first_active_row = 2, first_active_col = 2)
    }
  }

  wb_save(wb, path, overwrite = TRUE)
  invisible(path)
}
